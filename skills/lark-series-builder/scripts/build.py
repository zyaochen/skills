"""Assemble drafts/NN/seg/*.xml into drafts/NN/doc.xml, then lint it.

    python3 build.py 05            # build + full lint
    python3 build.py 05 --quiet    # build + only ERROR and SUMMARY lines

Inputs under drafts/NN/:
  refs.json       {"key": {"cite": "Author or org. Title. Venue (Year)", "url": "https://specific/page"}, ...}
  seg/s00.xml     title, 🎯 opening callout, position paragraph (if the series has one), 导读, 📎 分工
  seg/s01.xml ..  one numbered chapter h1 each, file-name order = reading order
  figs/NAME.svg   one SVG per figure (generated by figs/NAME.py)
Placeholders inside segments:
  {{r:key}} / {{r:k1,k2}}  -> <a href="URL">[n]</a>, n in first-use order over the whole doc
  {{C:NN}}                 -> <cite type="doc" …> to series doc NN (registry token and title)
  {{F:NAME}}               -> <whiteboard type="svg">figs/NAME.svg</whiteboard> (own line, never wrapped)
The reference list is generated; never write it in a segment. Unknown keys, docs or figures abort the build.
"""
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _series import ddir, docs, load, segs  # noqa: E402


def esc_attr(s):
    return s.replace('&', '&amp;').replace('"', '&quot;').replace('<', '&lt;')


def esc_text(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def build(cfg, num):
    d = ddir(cfg, num)
    refs = json.load(open(os.path.join(d, 'refs.json'), encoding='utf-8'))
    files = segs(cfg, num)
    if not files:
        sys.exit(f'no segments in {d}/seg/')
    body = ''.join(open(p, encoding='utf-8').read().strip() for p in files)
    reg = docs(cfg)
    errs, order = [], []

    def cite(m):
        out = []
        for key in [k.strip() for k in m.group(1).split(',')]:
            if key not in refs:
                errs.append(f'unknown ref key {key!r}')
                continue
            if key not in order:
                order.append(key)
            out.append(f'<a href="{esc_attr(refs[key]["url"])}">[{order.index(key) + 1}]</a>')
        return ''.join(out)

    def chap(m):
        n = m.group(1)
        if n not in reg:
            errs.append(f'unknown series doc {n}')
            return ''
        if n == num:
            errs.append(f'{{{{C:{n}}}}} points at this doc itself; write "第 N 章" for own chapters')
        c = reg[n]
        return f'<cite type="doc" doc-id="{c["token"]}" file-type="docx" title="{esc_attr(c["title"])}"></cite>'

    def fig(m):
        p = os.path.join(d, 'figs', m.group(1) + '.svg')
        if not os.path.exists(p):
            errs.append(f'missing figure figs/{m.group(1)}.svg')
            return ''
        svg = open(p, encoding='utf-8').read().strip()
        svg = re.sub(r'^<\?xml[^>]*\?>\s*', '', svg)
        svg = re.sub(r'^<whiteboard[^>]*>\s*|\s*</whiteboard>$', '', svg)
        return '<whiteboard type="svg">' + svg + '</whiteboard>'

    # writers sometimes wrap the figure placeholder in a paragraph or whiteboard; unwrap so tags are not doubled
    body = re.sub(r'<(?:whiteboard|p)\b[^>]*>\s*(\{\{F:[A-Za-z0-9_\-]+\}\})\s*</(?:whiteboard|p)>', r'\1', body)
    body = re.sub(r'\{\{r:([^}]+)\}\}', cite, body)
    body = re.sub(r'\{\{C:(?:[A-Za-z]+-)?(\d+)\}\}', chap, body)
    body = re.sub(r'\{\{F:([A-Za-z0-9_\-]+)\}\}', fig, body)
    left = re.findall(r'\{\{[^}]*\}\}', body)
    if left:
        errs.append(f'unresolved placeholders: {left[:5]}')
    if errs:
        sys.exit('BUILD ERROR\n' + '\n'.join(sorted(set(errs))))
    t = cfg['template']
    reflist = [f'<h1>{t["refs_h1"]}</h1>', f'<p>{t["refs_lead"].format(refs_asof=cfg.get("refs_asof", ""))}</p>']
    for i, key in enumerate(order, 1):
        r = refs[key]
        shown = re.sub(r'^https?://', '', r['url'])
        reflist.append(f'<p>[{i}] {esc_text(r["cite"])} <a href="{esc_attr(r["url"])}">{esc_text(shown)}</a></p>')
    xml = body + ''.join(reflist)
    open(os.path.join(d, 'doc.xml'), 'w', encoding='utf-8').write(xml)
    unused = [k for k in refs if k not in order]
    print(f'BUILD ok segments={len(files)} refs_used={len(order)} refs_unused={len(unused)} {unused[:10]}')


def main():
    cfg = load()
    num = sys.argv[1]
    build(cfg, num)
    here = os.path.dirname(os.path.abspath(__file__))
    lint = subprocess.run([sys.executable, os.path.join(here, 'lint_doc.py'), num], capture_output=True, text=True)
    out = lint.stdout + lint.stderr
    if '--quiet' in sys.argv:
        out = '\n'.join(ln for ln in out.splitlines() if ln.startswith(('ERROR', 'SUMMARY')))
    print(out)
    sys.exit(lint.returncode)


if __name__ == '__main__':
    main()
